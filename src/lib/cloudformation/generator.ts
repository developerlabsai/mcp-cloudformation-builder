/**
 * Generate outputs section
 */
function generateOutputs(analysis: AnalysisResult): Record<string, CloudFormationOutput> {
  const outputs: Record<string, CloudFormationOutput> = {};

  // Check what resources we have and add appropriate outputs
  const hasECS = analysis.awsServices.some(s =>
    s.service.toLowerCase().includes('ecs') || s.service.toLowerCase().includes('fargate')
  );
  const hasALB = analysis.awsServices.some(s =>
    s.service.toLowerCase().includes('alb') || s.service.toLowerCase().includes('load balancer')
  );
  const hasRDS = analysis.awsServices.some(s => s.service.toLowerCase().includes('rds'));
  const hasS3 = analysis.awsServices.some(s => s.service.toLowerCase().includes('s3'));

  if (hasALB) {
    outputs.ServiceURL = {
      Description: 'Application URL',
      Value: { 'Fn::GetAtt': ['ALB', 'DNSName'] },
    };
  }

  if (hasECS) {
    outputs.ClusterName = {
      Description: 'ECS Cluster Name',
      Value: { Ref: 'ECSCluster' },
    };
  }

  if (hasRDS) {
    outputs.DatabaseEndpoint = {
      Description: 'Database endpoint',
      Value: { 'Fn::GetAtt': ['RDSInstance', 'Endpoint.Address'] },
    };
  }

  if (hasS3) {
    outputs.AssetsBucket = {
      Description: 'S3 bucket for assets',
      Value: { Ref: 'S3Bucket' },
    };
  }

  return outputs;
}

/**
 * Convert object to YAML string
 */
function toYaml(obj: unknown, indent = 0): string {
  const spaces = '  '.repeat(indent);

  if (obj === null || obj === undefined) {
    return 'null';
  }

  if (typeof obj === 'string') {
    // Check if string needs quoting
    if (obj.includes(':') || obj.includes('#') || obj.includes('\n') || obj === '') {
      return `"${obj.replace(/"/g, '\\"')}"`;
    }
    return obj;
  }

  if (typeof obj === 'number' || typeof obj === 'boolean') {
    return String(obj);
  }

  if (Array.isArray(obj)) {
    if (obj.length === 0) return '[]';
    return obj
      .map(item => {
        const value = toYaml(item, indent + 1);
        if (typeof item === 'object' && item !== null) {
          return `${spaces}- ${value.trim().replace(/^\s+/, '')}`;
        }
        return `${spaces}- ${value}`;
      })
      .join('\n');
  }

  if (typeof obj === 'object') {
    const entries = Object.entries(obj);
    if (entries.length === 0) return '{}';

    return entries
      .map(([key, value]) => {
        if (value === undefined) return '';

        if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
          // Check for CloudFormation intrinsic functions
          const keys = Object.keys(value);
          if (keys.length === 1 && (keys[0] === 'Ref' || keys[0].startsWith('Fn::'))) {
            const fnKey = keys[0];
            const fnValue = (value as Record<string, unknown>)[fnKey];
            if (fnKey === 'Ref') {
              return `${spaces}${key}: !Ref ${fnValue}`;
            } else if (fnKey === 'Fn::Sub') {
              return `${spaces}${key}: !Sub ${toYaml(fnValue)}`;
            } else if (fnKey === 'Fn::GetAtt') {
              const [resource, attr] = fnValue as [string, string];
              return `${spaces}${key}: !GetAtt ${resource}.${attr}`;
            }
          }
        }

        const yamlValue = toYaml(value, indent + 1);
        if (typeof value === 'object' && value !== null) {
          return `${spaces}${key}:\n${yamlValue}`;
        }
        return `${spaces}${key}: ${yamlValue}`;
      })
      .filter(Boolean)
      .join('\n');
  }

  return String(obj);
}
